SIZES = ["8k", "32k", "128k", "512k"]
PRIMARY = (("A", "P"), ("128k", "512k"))
MAIN = {"P0": "main-P0", "P1": "main-P1", "P2": "main-P2", "P3": "main-P3"}
DEVICE = [("C3", "gpt-oss-120b", "Groq LPU", "device-C3-live"), ("C4", "gpt-oss-120b", "Cerebras WSE", "device-C4-sim"),
          ("C2", "qwen3.8-27b", "Groq LPU", "device-C2-live"), ("C5", "qwen3.8-27b", "Cerebras WSE", "device-C5-sim"),
          ("C1", "gpt-oss-20b", "Groq LPU", "device-C1-live"), ("C6", "qwen2.5-1.5b q4", "local CPU", "device-C6-live")]


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def money(x: float) -> str:
    return f"${x:.5f}" if x < 0.01 else f"${x:.4f}"


def table(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def cost_per_correct(recs: list[RunRecord], n_boot: int = 2000, seed: int = 42) -> tuple[float, float, float]:
    c = np.array([r.cost for r in recs])
    y = np.array([r.correct for r in recs], float)
    if not len(recs) or y.sum() == 0:
        return float("inf"), float("inf"), float("inf")
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(recs), size=(n_boot, len(recs)))
    boots = c[idx].sum(1) / np.maximum(y[idx].sum(1), 1)
    return float(c.sum() / y.sum()), float(np.quantile(boots, 0.025)), float(np.quantile(boots, 0.975))


def p95(xs: list[float]) -> float:
    return float(np.percentile(xs, 95)) if xs else float("nan")


def sel(recs: list[RunRecord], classes, sizes) -> list[RunRecord]:
    return [r for r in recs if r.cls in classes and r.size in sizes]


def ips(recs: list[RunRecord], policies: dict[str, str]) -> list[list[Any]]:
    """Inverse-propensity estimates of map-call accuracy under fixed policies, from the logged,
    partly random choices of the learned router."""
    calls = [s for r in recs for s in r.spans if s.role == "mapper" and s.ok and s.correct is not None
             and s.propensity]
    rows = []
    if not calls:
        return rows
    logged = np.mean([s.correct for s in calls])
    rows.append(["logged policy (P3)", len(calls), pct(logged), "direct average"])
    for name, cid in policies.items():
        w = [(1.0 / s.propensity) * float(s.correct) if s.candidate_id == cid else 0.0 for s in calls]
        n_match = sum(1 for s in calls if s.candidate_id == cid)
        rows.append([name, n_match, pct(min(1.0, float(np.mean(w)))) if n_match else "n/a",
                     "IPS; few matching calls, high variance" if n_match < 30 else "IPS"])
    return rows


def build_report(root: Path, cfg: dict) -> Path:
    runs_dir = root / cfg["runs_dir"]
    out_dir = root / "report"
    out_dir.mkdir(exist_ok=True)
    margin = cfg["margin_points"]
    md: list[str] = []
    runs: dict[str, list[RunRecord]] = {}
    metas: dict[str, dict] = {}
    for p, rid in MAIN.items():
        f = runs_dir / f"{rid}.jsonl.gz"
        if f.exists():
            metas[p], runs[p] = read_run(f)
    if not runs:
        raise FileNotFoundError(f"no main runs in {runs_dir} (expected {list(MAIN.values())})")
    any_meta = next(iter(metas.values()))
    md += ["# Mosaic report", "",
           "Generated by `mosaic report` from run records only (no provider calls). Every table names the run IDs "
           "its numbers come from; each run file records the git commit, config hash, data hash, seed and candidate "
           "model IDs.", "",
           f"Commit `{any_meta.get('git_commit')}` · data hash `{any_meta.get('data_hash')}` · seed {any_meta.get('seed')} "
           f"· margin {margin:g} points · one-sided 95% paired bootstrap (10,000 resamples) · Holm across cells.", "",
           "## Read this first: what is measured and what is simulated", "",
           "* **Live (real API calls, real clocks):** the device study, 12 questions at 8k on every candidate: Groq LPU "
           "(C1, C2, C3), Cerebras wafer-scale (C4, C5) and this machine's CPU through llama.cpp (C6), with plans written "
           "by gpt-oss-120b on Groq. Then a live validation slice on the Cerebras main pool: P0 against P3 on 20 "
           "aggregate and pairwise questions at 128k (section *Live validation*). These numbers are measurements.",
           "* **Simulated:** the full main evaluation (720 questions × 4 pipelines) and the router's training data, on "
           "the main pool C4, C5 (Cerebras) and C6, served by Mosaic's deterministic simulator in virtual time. Running "
           "it live would take about 15 hours of Cerebras quota per pipeline. The simulator's per-ticket error rates are "
           "**fitted from the live, oracle-labelled map calls of all six devices** (each set of weights shares one "
           "error model, fitted from both of its devices), and its latencies are the **measured** live profiles. Its "
           "long-context decay for direct calls remains an assumption, stated in `candidates.yaml`. The live "
           "validation slice checks the simulator against reality on the same questions.",
           "* Re-running `mosaic report` on the same run files reproduces this file byte for byte.", ""]

    # ---- headline -------------------------------------------------------------------------
    order = [p for p in ("P0", "P1", "P2", "P3") if p in runs]
    names = {"P0": "P0 direct", "P1": "P1 recursive, fixed", "P2": "P2 recursive, rules", "P3": "P3 recursive, learned"}
    md += ["## Headline: aggregate and pairwise questions at 128k and 512k", "",
           f"Pooled over the primary set (classes A and P, sizes 128k and 512k; runs {', '.join(MAIN[p] for p in order)}). "
           "P0 cannot read 512k (every window is about 131k tokens), so at 512k it answers from a corpus truncated to "
           "its window; that is recorded per question.", ""]
    rows, points = [], []
    for p in order:
        rs = sel(runs[p], *PRIMARY)
        k = sum(r.correct for r in rs)
        lo, hi = wilson(k, len(rs))
        cpc, clo, chi = cost_per_correct(rs)
        lat = [r.latency_ms for r in rs]
        rows.append([names[p], len(rs), f"{pct(k / max(1, len(rs)))} [{pct(lo)}, {pct(hi)}]", money(cpc),
                     f"[{money(clo)}, {money(chi)}]", f"{np.median(lat) / 1000:.1f} s", f"{p95(lat) / 1000:.1f} s",
                     sum(r.truncated for r in rs), sum(r.malformed for r in rs)])
        points.append((p, cpc, p95(lat), k / max(1, len(rs))))
    md += [table(["pipeline", "n", "accuracy [Wilson 95%]", "cost / correct", "95% CI", "p50 latency", "p95 latency",
                  "truncated", "malformed"], rows), ""]
    nd = charts.pareto(points, "P0", out_dir / "pareto.svg", "Primary set: cost per correct vs p95 latency (simulated main pool)")
    md += ["![Pareto](pareto.svg)", "",
           f"Non-dominated on (cost per correct, p95 latency, accuracy): {', '.join(sorted(nd))}. Baseline: P0.", ""]

    # ---- per-size accuracy ---------------------------------------------------------------
    md += ["## Accuracy by class and size", ""]
    for cls, label in (("L", "Lookup"), ("A", "Aggregate"), ("P", "Pairwise")):
        series, rows = {}, []
        for p in order:
            pts = []
            for size in SIZES:
                rs = sel(runs[p], (cls,), (size,))
                if rs:
                    k = sum(r.correct for r in rs)
                    lo, hi = wilson(k, len(rs))
                    pts.append((size, k / len(rs), lo, hi))
            series[p] = pts
            rows.append([p] + [f"{pct(a)} [{pct(lo)}–{pct(hi)}]" for _, a, lo, hi in pts])
        charts.accuracy_by_size(series, out_dir / f"accuracy_{cls}.svg", f"{label} questions (n=60 per cell)")
        md += [f"**{label} ({cls})**", "", table(["pipeline"] + SIZES[: len(rows[0]) - 1], rows), "",
               f"![{label}](accuracy_{cls}.svg)", ""]

    # ---- non-inferiority ------------------------------------------------------------------
    md += ["## Paired comparisons and non-inferiority verdicts", "",
           f"Verdict wording is fixed in advance: non-inferior = \"{WORDING['non-inferior'].format(m=margin)}\"; "
           "superior = \"Better than the baseline\"; inferior = \"Worse than the baseline\"; inconclusive = \"Not "
           "resolved by this sample\" (never \"equal\"). Differences are B − A in accuracy points. The primary "
           "analysis is pooled; the per-cell rows (60 questions each) are exploratory and Holm-adjusted.", ""]
    comps = [("P1", "P0", "Does recursion alone help?"), ("P2", "P1", "Does routing save cost without losing quality?"),
             ("P3", "P2", "Does learning beat rules?"), ("P3", "P0", "Primary claim: learned recursion vs the baseline")]
    primary_verdict = None
    disc_share = None
    for b, a, q in comps:
        if a not in runs or b not in runs:
            continue
        res = compare(runs[a], runs[b], margin=margin, pooled={"primary": PRIMARY})
        rows = []
        for v in res.get("primary", []) + res["cells"]:
            rows.append([f"**{v.cls} {v.size}**" if "+" in v.cls else f"{v.cls} {v.size}", v.n, pct(v.acc_a), pct(v.acc_b),
                         f"{v.diff:+.1f}", f"[{v.ci_low:+.1f}, {v.ci_high:+.1f}]",
                         f"{v.p_adj:.3g}" if v.p_adj is not None else f"{v.p_value:.3g}", v.outcome])
        md += [f"### {b} vs {a}: {q}", "", f"Runs: A = `{MAIN[a]}`, B = `{MAIN[b]}`.", "",
               table(["cell", "n", f"acc {a}", f"acc {b}", "diff", "one-sided 95% CI", "McNemar p (Holm)", "verdict"], rows), ""]
        if (b, a) == ("P3", "P0") and res.get("primary"):
            primary_verdict = res["primary"][0]
            pa = {r.question_id: r.correct for r in sel(runs["P0"], *PRIMARY)}
            pb = {r.question_id: r.correct for r in sel(runs["P3"], *PRIMARY)}
            disc_share = np.mean([pa[k] != pb[k] for k in pa if k in pb])

    # ---- sample size ----------------------------------------------------------------------
    if disc_share is not None:
        n = primary_verdict.n
        hw = ci_half_width(disc_share, n) * 100
        md += ["## Sample size: the honest arithmetic", "",
               f"On the primary set {n} questions are paired and {pct(disc_share)} of pairs disagree, so the CI half-width "
               f"is about ±{hw:.1f} points (1.96·√(p_disc/n)). A 2-point margin would need about "
               f"{n_for_half_width(max(disc_share, 0.01), 0.02):,} paired questions at this discordance, and a 5-point "
               f"margin about {n_for_half_width(max(disc_share, 0.01), 0.05):,}. The PRD expected ~10% discordance; "
               "here the baseline fails so often at 128k+ that discordance is far higher, which is why the verdict is "
               "decisive despite the wide interval.", ""]

    # ---- cost and latency per class -------------------------------------------------------
    rows = []
    for cls in "LAP":
        for size in SIZES:
            row = [f"{cls} {size}"]
            for p in order:
                rs = sel(runs[p], (cls,), (size,))
                cpc = cost_per_correct(rs, n_boot=200)[0] if rs else float("nan")
                row.append(f"{money(cpc) if np.isfinite(cpc) else '—'} · {p95([r.latency_ms for r in rs]) / 1000:.1f}s" if rs else "—")
            rows.append(row)
    md += ["## Cost per correct answer and p95 latency per cell", "",
           "Cost is measured tokens × configured list prices (free-tier calls priced at list price); CPU calls are "
           "priced as electricity plus amortisation. Latency is the critical path per question (plan + filter + "
           "slowest map wave + reduce), computed from spans. In virtual time the simulated user asks the next question "
           "a minute after each answer, so rate-limit queueing within a question is real but backlog across questions "
           "is not.", "",
           table(["cell"] + [f"{p}: $/correct · p95" for p in order], rows), ""]

    # ---- router diagnostics ---------------------------------------------------------------
    if "P3" in runs:
        md += router_section(runs, root, cfg)
    md += lookup_section(runs)
    md += live_validation_section(runs_dir, runs, margin)
    md += device_section(root, runs_dir, out_dir)
    md += calibration_section(root)
    md += metrics_section(runs, primary_verdict, root, cfg, margin)
    md += limitations()
    path = out_dir / "report.md"
    path.write_text("\n".join(md) + "\n")
    return path


def router_section(runs: dict[str, list[RunRecord]], root: Path, cfg: dict) -> list[str]:
    md = ["## Router diagnostics (P3, learned)", ""]
    spans = [s for r in runs["P3"] for s in r.spans if s.candidate_id and s.role != "question"]
    by = Counter((s.role, s.candidate_id) for s in spans if s.ok)
    roles = sorted({k[0] for k in by})
    cands = sorted({k[1] for k in by})
    rows = [[role] + [by.get((role, c), 0) for c in cands] + [sum(by.get((role, c), 0) for c in cands)] for role in roles]
    md += ["Calls per role and candidate (successful calls; run `main-P3`):", "",
           table(["role"] + cands + ["total"], rows), ""]
    for p in ("P2", "P1"):
        if p in runs:
            sp = [s for r in runs[p] for s in r.spans if s.candidate_id and s.ok and s.role == "mapper"]
            c = Counter(s.candidate_id for s in sp)
            md += [f"For contrast, {p} mapper calls: " + ", ".join(f"{k} {v} ({pct(v / max(1, len(sp)))})"
                                                                   for k, v in sorted(c.items())) + ".", ""]
    maps = [s for s in spans if s.role == "mapper" and s.ok]
    flagged = sum(1 for s in maps if "no candidate clears bar" in s.note)
    fallbacks = sum(1 for s in spans if not s.ok)
    md += [f"{flagged} mapper calls ({pct(flagged / max(1, len(maps)))}) had no candidate above the bar and were flagged; "
           f"{fallbacks} failed calls fell back to the next candidate.", ""]
    lab = [s for s in maps if s.correct is not None and s.q_hat is not None]
    if lab:
        q = np.array([s.q_hat for s in lab])
        y = np.array([float(s.correct) for s in lab])
        from mosaic.routing.predictor import brier, reliability
        rel = reliability(q, y)
        md += [f"Predicted vs realised quality on evaluation map calls (not used for training): mean predicted "
               f"{q.mean():.3f}, observed {y.mean():.3f}, Brier {brier(q, y):.4f} vs constant {brier(np.full(len(y), y.mean()), y):.4f}.", ""]
        lat = [(s.l_hat, s.total_ms + s.queue_ms) for s in maps if s.l_hat]
        cst = [(s.c_hat, s.cost) for s in maps if s.c_hat is not None]
        if lat:
            ratio = np.median([b / a for a, b in lat if a > 0])
            md += [f"Predicted vs realised mapper latency: median realised/predicted = {ratio:.2f}; cost: "
                   f"{sum(b for _, b in cst) / max(1e-12, sum(a for a, _ in cst)):.2f} (realised/predicted, total).", ""]
    rep_path = root / "router" / "model.json"
    if rep_path.exists():
        rep = json.loads(rep_path.read_text())["report"]
        rows, curves = [], {}
        for k, r in sorted(rep.items()):
            rows.append([k, r["kind"], r["n_train"], r["n_test"], f"{r['base_rate']:.3f}", f"{r['brier']:.4f}",
                         f"{r['brier_constant']:.4f}", "yes" if r["beats_constant"] else "**no**",
                         "isotonic" if r["calibrated_isotonic"] else "none", f"{100 * r['max_bin_gap']:.1f}"])
            if k.startswith("mapper"):
                curves[k] = r["reliability"]
        charts.reliability(curves, root / "report" / "reliability.svg", "Held-out reliability, mapper predictors")
        md += ["### Predictor calibration (held-out profiling data)", "",
               "One logistic regression per (role, candidate) on profiling labels (separate questions and corpora from "
               "the evaluation). Isotonic scaling is applied only when the held-out gap is large and it lowers Brier.", "",
               table(["role|candidate", "model", "n train", "n test", "base rate", "Brier", "Brier const", "beats const",
                      "calibration", "max bin gap (pts)"], rows), "", "![Reliability](reliability.svg)", ""]
        coef = {k: r["coef"] for k, r in rep.items() if r.get("coef")}
        if coef:
            feats = sorted({f for c in coef.values() for f in c})
            md += ["Standardised coefficients (positive = more likely correct):", "",
                   table(["feature"] + sorted(coef), [[f] + [f"{coef[k].get(f, 0):+.2f}" for k in sorted(coef)] for f in feats]), ""]
    px = root / cfg["runs_dir"] / "main-P3x.jsonl.gz"
    if px.exists():
        _, rx = read_run(px)
        a3, ax = np.mean([r.correct for r in runs["P3"]]), np.mean([r.correct for r in rx])
        p3 = {r.question_id: r.correct for r in runs["P3"]}
        hurt = sum(1 for r in rx if p3.get(r.question_id) and not r.correct)
        md += ["### Exploration, and what it costs", "",
               "The evaluation run `main-P3` is the learned policy with exploration off. A second run, `main-P3x`, sends "
               f"{cfg['explore_rate']:.0%} of calls to a random feasible candidate and logs the propensity. Exploring "
               f"cost {100 * (a3 - ax):.1f} accuracy points overall ({pct(a3)} → {pct(ax)}; {hurt} questions flipped "
               "from right to wrong): one question fans out into up to ~180 map calls, so per-call exploration "
               "almost always touches some call of a large question, and one bad chunk breaks an exact answer. "
               "Exploration belongs on a profiling stream or under a per-question budget, not on every call.", "",
               "Inverse-propensity estimates of how fixed mapper policies would have done on the logged calls of "
               "`main-P3x`, without re-running them:", "",
               table(["policy", "matching calls", "estimated map-call accuracy", "note"],
                     ips(rx, {"always C5": "C5", "always C4": "C4", "always C6": "C6"})), ""]
    return md


def lookup_section(runs: dict[str, list[RunRecord]]) -> list[str]:
    md = ["## Lookups: does the system take the direct path? (M4)", ""]
    rows = []
    for p in ("P1", "P2", "P3"):
        if p not in runs:
            continue
        ls = [r for r in runs[p] if r.cls == "L"]
        d = sum(1 for r in ls if r.plan and r.plan.get("strategy") == "direct")
        iso = sum(1 for r in ls if r.plan and r.plan.get("strategy") == "direct" and r.plan["filter"]["fields"])
        rows.append([p, len(ls), pct(d / max(1, len(ls))), pct(iso / max(1, len(ls))), pct(np.mean([r.correct for r in ls]))])
    md += [table(["pipeline", "lookups", "direct strategy", "direct + filter isolating the ticket", "accuracy"], rows), "",
           "The planner (shared by P1–P3) decides the strategy; the router then places the single direct call.", ""]
    return md


def live_validation_section(runs_dir: Path, runs: dict[str, list[RunRecord]], margin: float) -> list[str]:
    """P0 vs P3 on real Cerebras calls, next to what the simulator predicted for the same questions."""
    files = {p: runs_dir / f"live-{p}-128k.jsonl.gz" for p in ("P0", "P3")}
    if not all(f.exists() for f in files.values()):
        return []
    live = {p: read_run(f)[1] for p, f in files.items()}
    md = ["## Live validation on Cerebras", "",
          "P0 (C5 reads the corpus, trimmed to its window) and P3 (learned router over C4, C5 and C6, all live) on the "
          "same 20 questions: the first 10 aggregate and 10 pairwise questions at 128k, real clocks, real quotas. Runs "
          "`live-P0-128k` and `live-P3-128k`; the simulated columns are the same questions in `precal-*-slice` "
          "(before recalibration) and `main-P0` / `main-P3` (after); \"agree\" = same right/wrong outcome per question.", ""]
    rows = []
    for p in ("P0", "P3"):
        lr = live[p]
        ids = {r.question_id for r in lr}
        sr = {r.question_id: r for r in runs.get(p, []) if r.question_id in ids}
        agree = np.mean([sr[r.question_id].correct == r.correct for r in lr if r.question_id in sr]) if sr else float("nan")
        pf = runs_dir / f"precal-{p}-slice.jsonl.gz"
        pre = {r.question_id: r for r in read_run(pf)[1]} if pf.exists() else {}
        pre_agree = np.mean([pre[r.question_id].correct == r.correct for r in lr if r.question_id in pre]) if pre else float("nan")
        lat = [r.latency_ms for r in lr]
        own = [r.latency_ms - min((s for s in r.spans if s.candidate_id), key=lambda s: s.start_ms).queue_ms for r in lr]
        rows.append([p, len(lr), pct(np.mean([r.correct for r in lr])),
                     f"{pct(np.mean([x.correct for x in pre.values()]))} ({pct(pre_agree)} agree)" if pre else "—",
                     f"{pct(np.mean([x.correct for x in sr.values()]))} ({pct(agree)} agree)" if sr else "—",
                     money(cost_per_correct(lr, n_boot=500)[0]), f"{np.median(lat) / 1000:.1f} / {p95(lat) / 1000:.1f} s",
                     f"{np.median(own) / 1000:.1f} / {p95(own) / 1000:.1f} s", sum(r.truncated for r in lr)])
    md += [table(["pipeline", "n", "live accuracy", "simulated, before (out of sample)", "simulated, after recalibration",
                  "live cost / correct", "latency p50 / p95", "from first admission p50 / p95", "truncated"], rows), "",
           "Live questions ran back to back, so a question's first call often waited for the previous question's "
           "tokens to leave the 150k-a-minute window. *From first admission* subtracts that carry-over; queueing "
           "inside the question (a fan-out exceeding the quota) stays in.", "",
           "**What the validation caught.** Before seeing this slice, the simulator predicted 80% for P3 here and live "
           "gave 60%. Six of P3's eight live misses were tone counts. The device study had held only 3 tone "
           "observations, so the simulator's tone error rate (about 1% per ticket) was almost pure prior; the live "
           "slice measured about 5% for Qwen (29 errors in 379). Part of that is the data, not the model: every "
           "ticket reports a problem, and a \"positive\" ticket differs only by a polite closing line, so tone "
           "labels are ambiguous by construction. The simulator was then recalibrated on these live calls "
           "(`precal-*-slice` keeps the before-predictions), so the *after* column is in-sample for these 20 "
           "questions; its value is that the other 700 simulated questions now carry the measured tone error rate.", "",
           "**A second catch.** Recalibrated on that slice, the simulator briefly favoured gpt-oss-120b (C4) for tone: "
           "C4's tone rate still rested on 6 observations, so it was nearly all prior, and the learned router exploited "
           "it (22 of its 31 wins over the rules were tone questions). A targeted live run on the same 7 tone questions "
           "(`tone-C4-live`, `tone-C5-live`) scored C4 0/7 and C5 1/7, and measured C4's tone error at 15% per ticket, "
           "3× Qwen's. With that in the fit, the learned router's advantage disappeared. Lesson: a learned router finds "
           "and exploits whichever parameter has the least evidence, so every routing gain needs its evidence checked "
           "live.", ""]
    v = compare(live["P0"], live["P3"], margin=margin, pooled={"all": (("A", "P"), ("128k",))})["all"][0]
    md += [f"Paired on these 20 questions, P3 − P0 = {v.diff:+.1f} points (one-sided 95% CI [{v.ci_low:+.1f}, "
           f"{v.ci_high:+.1f}], McNemar p = {v.p_value:.3g}): **{v.outcome}** — "
           f"\"{WORDING[v.outcome].format(m=margin)}\". With n = 20 this is a check that the simulated verdict "
           "survives contact with the real API, not a replacement for the 240-question analysis.", ""]
    spans = [s for r in live["P3"] for s in r.spans if s.candidate_id and s.ok]
    by = Counter((s.role, s.candidate_id) for s in spans)
    md += ["Live P3 calls by role and candidate: " + ", ".join(f"{r} {c} ×{n}" for (r, c), n in sorted(by.items())) + ".", ""]
    return md


def device_section(root: Path, runs_dir: Path, out_dir: Path) -> list[str]:
    md = ["## Device study: same weights, different silicon", "",
          "P1 (every executor call on one candidate) on the same 12 questions at 8k (4 per class), with the same plans "
          "(written once by gpt-oss-120b on Groq and replayed from the cache). Service time = time from admission to "
          "last token; queue = time waiting for the free-tier token budget.", ""]
    rows, lat_rows, used = [], [], []
    for cid, model, dev, rid in DEVICE:
        live_f = runs_dir / f"{rid.replace('-sim', '-live')}.jsonl.gz"
        if live_f.exists():  # a live run supersedes the simulated row
            rid = rid.replace("-sim", "-live")
        f = runs_dir / f"{rid}.jsonl.gz"
        used.append(rid)
        if not f.exists():
            rows.append([cid, model, dev, "not run", "", "", "", "", "", "", "", ""])
            continue
        meta, recs = read_run(f)
        src = "live" if meta.get("backends", {}).get(cid) == "live" else "simulated"
        maps = [s for r in recs for s in r.spans if s.candidate_id == cid and s.role in ("mapper", "direct") and s.ok]
        svc = [s.total_ms for s in maps]
        ttft = [s.ttft_ms for s in maps]
        from mosaic.routing.profiler import summarize
        prof = summarize(maps, cid, 1, src)
        buffered = np.median([s.total_ms - s.ttft_ms for s in maps]) < 20 if maps else False
        dec = [s.tokens_out / ((s.total_ms - s.ttft_ms) / 1000) for s in maps if s.total_ms - s.ttft_ms > 20 and s.tokens_out > 5]
        q = [s.queue_ms for s in maps]
        rsn = sum(s.reasoning_tokens for s in maps) / max(1, sum(s.tokens_out for s in maps))
        mc = [s.correct for s in maps if s.role == "mapper" and s.correct is not None]
        rows.append([cid, model, dev, src, len(recs), pct(np.mean([r.correct for r in recs])),
                     f"{np.mean(mc):.0%} of {len(mc)}" if mc else "—",
                     f"{np.percentile(ttft, 50):.0f} / {np.percentile(ttft, 95):.0f}" if ttft else "—",
                     f"{np.percentile(svc, 50):.0f} / {np.percentile(svc, 95):.0f}" if svc else "—",
                     (f"{prof.tps_out:.0f} (fit, buffered)" if buffered else f"{np.median(dec):.0f}") if prof and (buffered or dec) else "—",
                     f"{np.mean(q) / 1000:.1f} s", pct(rsn)])
        if svc:
            lat_rows.append((f"{cid} {model} · {dev}", float(np.percentile(svc, 50)), float(np.percentile(svc, 95)),
                             "live" if src == "live" else "sim"))
    md += [table(["id", "weights", "device", "source", "questions", "accuracy", "map calls fully correct",
                  "TTFT p50/p95 ms", "service p50/p95 ms", "decode tok/s", "mean queue", "reasoning share of output"], rows), "",
           "Decode speed is the median of output tokens over (service time − TTFT) per call. *Buffered*: the provider "
           "sent the whole JSON answer in one chunk (Groq's Qwen in JSON mode), so TTFT equals service time and the "
           "speed is instead fitted from service time against input and output tokens across the run's calls.", ""]
    if lat_rows:
        charts.device_latency(lat_rows, out_dir / "device_latency.svg", "Device study: map and direct call service time")
        md += ["![Device latency](device_latency.svg)", "",
               "Runs: " + ", ".join(f"`{r}`" for r in used) + ". With 12 questions the accuracy columns are "
               "anecdotal; the latency rows rest on every call in the run. Question latency in these runs also carries "
               "the planner call's original Groq free-tier queue (replayed from the cache identically for every "
               "device), so compare devices on the call columns, not on question latency.", "",
               "**Same weights did not mean same answers.** Qwen 3.8 27B gave identical question-level results on Groq "
               "and Cerebras. gpt-oss-120b on Cerebras (C4) missed two questions it got right on Groq (C3): a tone count "
               "(0 instead of 2), and a lookup where the ticket says \"Please refund the $59.99\" and the question asks "
               "what refund it *received*. There C4 took the stricter reading (a request is not a refund received), "
               "while the oracle counts requests. Qwen on Cerebras reasons by default, unlike on Groq, so C5 is run with "
               "`reasoning_effort: none` to keep the comparison like for like.", ""]
    return md


def calibration_section(root: Path) -> list[str]:
    from mosaic.config import load_candidates
    cands = load_candidates(root / "candidates.yaml")
    rows = []
    for c in cands.values():
        sm = c.sim
        def cell(k: str) -> str:
            if k not in sm:
                return "—"
            n = sm.get(f"{k}_n")
            return f"{sm[k]:.4f}" + (f" (n={n})" if n else "")
        rows.append([c.id, sm.get("weights"), "fitted" if sm.get("calibrated_from") else "prior", cell("err_category"),
                     cell("err_refund"), cell("err_sentiment"), cell("drop"), cell("malformed")])
    prof = root / "profiles" / "profiles.parquet"
    md = ["## Simulator error model (fitted from live calls)", "",
          "Per-ticket, per-field error rates the simulator uses, normalised by its context-rot factor (1 + chunk "
          "tokens / 6000). Fitted by `mosaic calibrate` from the live device runs as posterior means under a Beta prior "
          "worth 50 observations, counting each distinct call once; n = ticket-field observations behind each rate. "
          "Thin rows (sentiment: 3 observations) stay near the prior. Live errors were systematic per phrasing (the "
          "same template misread every time), which an independent per-ticket model understates.", "",
          table(["id", "weights", "source", "category", "refund flag and amount", "sentiment", "dropped row",
                 "malformed call"], rows), ""]
    if prof.exists():
        df = pd.read_parquet(prof)
        md += ["Latency profiles used by the router (`profiles/profiles.parquet`):", "",
               table(["candidate", "concurrency", "source", "TTFT p50", "TTFT p95", "TTFT base", "prefill tok/s", "decode tok/s",
                      "error rate", "calls"],
                     [[r.candidate_id, r.concurrency, r.source, f"{r.ttft_p50:.0f}", f"{r.ttft_p95:.0f}", f"{r.ttft_base:.0f}",
                       f"{r.prefill_tps:.0f}", f"{r.tps_out:.0f}", f"{r.error_rate:.3f}", r.n_calls] for r in df.itertuples()]), ""]
    return md


def metrics_section(runs, primary, root: Path, cfg: dict, margin: float) -> list[str]:
    rows = []
    if primary is not None:
        rows.append(["M1 accuracy, A+P at 128k+", f"non-inferior, {margin:g}-point margin",
                     f"diff {primary.diff:+.1f}, CI low {primary.ci_low:+.1f} → {primary.outcome}",
                     "met" if primary.outcome in ("non-inferior", "superior") else "not met"])
    if "P0" in runs and "P3" in runs:
        c0 = cost_per_correct(sel(runs["P0"], *PRIMARY))[0]
        c3 = cost_per_correct(sel(runs["P3"], *PRIMARY))[0]
        rows.append(["M2 cost per correct", "≤ 1/3 of baseline", f"{money(c3)} vs {money(c0)} ({c3 / c0:.2f}×)",
                     "met" if c3 <= c0 / 3 else "not met"])
        l0 = p95([r.latency_ms for r in sel(runs["P0"], *PRIMARY)])
        l3 = p95([r.latency_ms for r in sel(runs["P3"], *PRIMARY)])
        rows.append(["M3 p95 latency", "no worse than baseline", f"{l3 / 1000:.1f} s vs {l0 / 1000:.1f} s",
                     "met" if l3 <= l0 else "not met"])
    if "P3" in runs:
        ls = [r for r in runs["P3"] if r.cls == "L"]
        d = np.mean([bool(r.plan and r.plan.get("strategy") == "direct") for r in ls]) if ls else 0
        rows.append(["M4 direct path on lookups", "≥ 90%", pct(d), "met" if d >= 0.9 else "not met"])
    rep_path = root / "router" / "model.json"
    if rep_path.exists():
        rep = json.loads(rep_path.read_text())["report"]
        mains = {k: v for k, v in rep.items() if k.split("|")[1] in cfg["main_pool"] and v["kind"] == "logistic"}
        beats = all(v["beats_constant"] for v in mains.values())
        gaps = max((v["max_bin_gap"] for v in mains.values()), default=0)
        rows.append(["M5 calibration", "Brier < constant; bins within 10 pts",
                     f"{sum(v['beats_constant'] for v in mains.values())}/{len(mains)} beat constant; worst bin gap {100 * gaps:.1f} pts",
                     "met" if beats and gaps <= 0.10 else "partly met" if beats else "not met"])
    vf = root / "report" / "verify.json"
    if vf.exists():
        v = json.loads(vf.read_text())
        rows.append(["M6 reproducibility", "cached re-run reproduces every number", v.get("summary", ""),
                     "met" if v.get("ok") else "partly met" if v.get("explained_only") else "not met"])
    cov = root / "report" / "code_stats.json"
    if cov.exists():
        c = json.loads(cov.read_text())
        rows.append(["M7 code size and tests", "< ~2,500 core lines; ≥ 80% coverage on core",
                     f"{c['core_lines']:,} core lines; {c['coverage']:.0f}% coverage; {c['tests']} tests",
                     "met" if c["core_lines"] <= 2700 and c["coverage"] >= 80 else "partly met"])
    return ["## Success metrics (hypotheses, reported whichever way they land)", "",
            "M1–M5 use the simulated main pool (see the first section); the live validation slice reports the same "
            "comparison on real Cerebras calls.", "",
            table(["metric", "target", "result", "status"], rows), ""]


